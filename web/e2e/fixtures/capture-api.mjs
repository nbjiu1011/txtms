const VIEWS = ["MY_DRAFT", "MY_CONFIRMING", "MY_REVIEW", "WAITING_ASSIGNMENT", "APPROVAL_PENDING"];

async function login(userId) {
  const res = await fetch(`${API}/auth/demo-login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ userId }),
  });
  if (!res.ok) throw new Error(`demo-login ${userId}: ${res.status}`);
  return res.json();
}

const personas = await (await fetch(`${API}/auth/demo-personas`)).json();
const snapshot = {};
const typed = [];
for (const [uid, paths] of Object.entries(PLAN)) {
  const { accessToken, me } = await login(Number(uid));
  const responses = { "/me": me, "/customers": null };
  const get = async (path) => {
    const res = await fetch(API + path, { headers: { Authorization: `Bearer ${accessToken}` } });
    return res.ok ? res.json() : { __status: res.status, ...(await res.json().catch(() => ({}))) };
  };
  responses["/customers"] = await get("/customers");
  for (const view of VIEWS) {
    for (const size of [1]) {
      const path = `/requests?projectId=1&view=${view}&page=0&size=${size}`;
      responses[path] = await get(path);
    }
  }
  for (const [path, exp] of Object.entries(paths)) {
    const body = await get(path);
    if (exp) {
      typed.push(`export const ${exp[0]}: ${exp[1]} = ${JSON.stringify(body, null, 2)};`);
      responses[path] = { __ref: exp[0] };
    } else {
      responses[path] = body;
    }
  }
  snapshot[uid] = responses;
}

const refs = JSON.stringify(snapshot, null, 2).replace(/\{\s*"__ref": "(\w+)"\s*\}/g, "$1");
