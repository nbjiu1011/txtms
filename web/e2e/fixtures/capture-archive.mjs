/**
 * Regenerates `archive-snapshot.ts` (콘텐츠 archive of project 1 as 김서연) from a running API in demo
 * mode. Only seed lineages are kept (`REQ-2609-*`): requests created by the real-API flows would make
 * the comparison with the reference prototype depend on the dev DB. Usage:
 *   node e2e/fixtures/capture-archive.mjs [http://localhost:8080]
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const API = (process.argv[2] ?? "http://localhost:8080") + "/api";
const SEED = /^REQ-2609-/;

const res = await fetch(`${API}/auth/demo-login`, {
  method: "POST",
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify({ userId: 1 }),
});
if (!res.ok) throw new Error(`demo-login: ${res.status}`);
const { accessToken } = await res.json();
const get = async (path) => {
  const r = await fetch(API + path, { headers: { Authorization: `Bearer ${accessToken}` } });
  if (!r.ok) throw new Error(`${path}: ${r.status}`);
  return r.json();
};

const page = await get("/archive/contents?projectId=1&page=0&size=100");
const content = page.content
  .filter((line) => SEED.test(line.lineKey) && SEED.test(line.latest.requestId))
  .map((line) => ({ ...line, followUps: line.followUps.filter((f) => SEED.test(f.requestId)) }));
const campaigns = [...new Set(content.flatMap((line) => line.campaigns))].sort((a, b) => a.localeCompare(b, "ko"));
const lines = {
  content,
  page: { number: 0, size: 20, totalElements: content.length, totalPages: content.length ? 1 : 0 },
};

const out = `// Generated by e2e/fixtures/capture-archive.mjs from the demo API (seed lineages only). Do not edit by hand.
import type { ArchiveLine } from "@/entities/request";
import type { Page } from "@/shared/api";

export const ARCHIVE_CAPTURED_AT = ${JSON.stringify(new Date().toISOString())};

/** \`GET /api/archive/contents?projectId=1&size=20&page=0\` as 김서연 (seed lineages). */
export const archiveContentsU1: Page<ArchiveLine> = ${JSON.stringify(lines, null, 2)};

/** \`GET /api/archive/campaigns?projectId=1\`. */
export const archiveCampaignsU1: string[] = ${JSON.stringify(campaigns)};

/** Extra GET responses for \`mockApiAs(page, 1, { extra })\`. */
export const ARCHIVE_EXTRA_U1: Record<string, unknown> = {
  "/archive/contents?projectId=1&size=20&page=0": archiveContentsU1,
  "/archive/campaigns?projectId=1": archiveCampaignsU1,
};
`;
writeFileSync(fileURLToPath(new URL("./archive-snapshot.ts", import.meta.url)), out);
console.log(`wrote archive-snapshot.ts (${content.length} lines)`);
