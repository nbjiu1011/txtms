/**
 * Captures the 검수 / 승인 screen responses (list views, workload, request details) from a running API
 * in demo mode into `review-snapshot.ts`. Lists keep the demo seed requests only (`REQ-2609-*`) so
 * requests created by flow scripts do not leak into the visual comparison.
 *   node e2e/fixtures/capture-review.mjs [http://localhost:4245]
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const API = (process.argv[2] ?? "http://localhost:4245") + "/api";
const SEED = /^REQ-2609-/;

const list = (view) => `/requests?projectId=1&view=${view}&page=0&size=100`;
/** persona → paths (lists are filtered to the seed). */
const PLAN = {
  2: [list("MY_ASSIGNED_ACTIVE"), list("MY_ASSIGNED_DONE")],
  3: [
    list("MY_ASSIGNED_ACTIVE"),
    list("MY_ASSIGNED_DONE"),
    list("WAITING_ASSIGNMENT"),
    list("OVERDUE"),
    list("DUE_SOON"),
    "/projects/1/workload",
    "/requests/REQ-2609-104",
    "/requests/REQ-2609-104/history",
    "/requests/REQ-2609-101",
    "/requests/REQ-2609-101/history",
  ],
  4: [list("APPROVAL_QUEUE"), list("APPROVAL_PENDING"), list("APPROVAL_PROCESSED")],
};

async function login(userId) {
  const res = await fetch(`${API}/auth/demo-login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ userId }),
  });
  if (!res.ok) throw new Error(`demo-login ${userId}: ${res.status}`);
  return res.json();
}

const out = {};
for (const [uid, paths] of Object.entries(PLAN)) {
  const { accessToken } = await login(Number(uid));
  out[uid] = {};
  for (const path of paths) {
    const res = await fetch(API + path, { headers: { Authorization: `Bearer ${accessToken}` } });
    let body = await res.json();
    if (!res.ok) body = { __status: res.status, ...body };
    if (body && Array.isArray(body.content)) {
      const content = body.content.filter((r) => SEED.test(r.id));
      body = { content, page: { ...body.page, totalElements: content.length, totalPages: content.length ? 1 : 0 } };
    }
    out[uid][path] = body;
  }
}

const file = `// Generated by e2e/fixtures/capture-review.mjs from the demo API (seed requests only). Do not edit by hand.
export const REVIEW_CAPTURED_AT = ${JSON.stringify(new Date().toISOString())};

/** userId → extra GET responses of the 검수 / 승인 screens (merged into \`mockApiAs\` with \`extra\`). */
export const REVIEW_SNAPSHOT: Record<number, Record<string, unknown>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(fileURLToPath(new URL("./review-snapshot.ts", import.meta.url)), file);
console.log("wrote review-snapshot.ts");
