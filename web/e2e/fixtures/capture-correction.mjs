/**
 * Captures correction responses for the visual comparison into `correction-snapshot.ts`: the dataset
 * label of the seed requests the screens open (as 김서연, who can open them all), and the check result
 * of REQ-2609-101 (all contents) as 박지훈.
 *   node e2e/fixtures/capture-correction.mjs [http://localhost:4245]
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const API = (process.argv[2] ?? "http://localhost:4245") + "/api";
const DATASET_IDS = ["REQ-2609-101", "REQ-2609-103", "REQ-2609-088", "REQ-2609-105", "REQ-2609-104"];

async function call(token, method, path, body) {
  const res = await fetch(API + path, {
    method,
    headers: { Authorization: `Bearer ${token}`, ...(body ? { "Content-Type": "application/json" } : {}) },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) throw new Error(`${method} ${path}: ${res.status} ${await res.text()}`);
  return res.json();
}

async function token(userId) {
  const res = await fetch(`${API}/auth/demo-login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ userId }),
  });
  return (await res.json()).accessToken;
}
const accessToken = await token(2);
const requester = await token(1);

const datasets = {};
for (const id of DATASET_IDS) datasets[`/requests/${id}/corrections/dataset`] = await call(requester, "GET", `/requests/${id}/corrections/dataset`);
const detail = await call(accessToken, "GET", "/requests/REQ-2609-101");
const check = await call(accessToken, "POST", "/requests/REQ-2609-101/corrections/check", {
  contents: detail.contents.map((c) => ({ contentKey: c.key, payload: c.payload, hasFiles: c.files.length > 0 })),
});
for (const r of check.results) r.checkedAt = "2026-10-07T05:00:00Z";

const out = `// Generated by e2e/fixtures/capture-correction.mjs — do not edit by hand.
import type { CorrectionDataset, CorrectionResult } from "@/entities/correction";

/** Dataset labels of the seed requests the visual screens open (GET extras). */
export const CORRECTION_DATASETS: Record<string, CorrectionDataset> = ${JSON.stringify(datasets, null, 2)};

/** \`POST /requests/REQ-2609-101/corrections/check\` for C1–C3 as 박지훈. */
export const CHECK_101: { results: CorrectionResult[] } = ${JSON.stringify(check, null, 2)};
`;
writeFileSync(fileURLToPath(new URL("./correction-snapshot.ts", import.meta.url)), out);
console.log(`correction-snapshot.ts: ${Object.keys(datasets).length} datasets, ${check.results.length} results`);
