/**
 * Regenerates `draft-snapshot.ts` (REQ-2609-105 as 김서연 + the project 1 variables) from a running API in
 * demo mode. Run it on a freshly seeded database (the real-API flows edit REQ-2609-105). Usage:
 *   node e2e/fixtures/capture-draft.mjs [http://localhost:4245]
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const API = (process.argv[2] ?? "http://localhost:4245") + "/api";

const login = await fetch(`${API}/auth/demo-login`, {
  method: "POST",
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify({ userId: 1 }),
});
if (!login.ok) throw new Error(`demo-login 1: ${login.status}`);
const { accessToken } = await login.json();

async function get(path) {
  const res = await fetch(API + path, { headers: { Authorization: `Bearer ${accessToken}` } });
  if (!res.ok) throw new Error(`${path}: ${res.status}`);
  return res.json();
}

const detail = await get("/requests/REQ-2609-105");
const history = await get("/requests/REQ-2609-105/history");
const variables = await get("/projects/1/variables");

const out = `// Generated by e2e/fixtures/capture-draft.mjs from the demo API (contract shapes). Do not edit by hand.
import type { HistoryEntry, RequestDetail } from "@/entities/request";
import type { Variable } from "@/entities/variable";

export const request105U1: RequestDetail = ${JSON.stringify(detail, null, 2)};

export const history105: HistoryEntry[] = ${JSON.stringify(history, null, 2)};

export const variablesP1: Variable[] = ${JSON.stringify(variables, null, 2)};
`;
writeFileSync(fileURLToPath(new URL("./draft-snapshot.ts", import.meta.url)), out);
console.log("wrote draft-snapshot.ts");
